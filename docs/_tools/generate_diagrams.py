import html
import os

OUT_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "activity-diagrams")

LANE_W = 260
NODE_W = 200
Y0 = 120
GAP = 96
ACTION_H = 46
DEC_H = 84
SE_H = 36
BAR_H = 10


def kind_of(nid):
    if nid == "s" or nid.startswith("start"):
        return "start"
    if nid == "e" or nid.startswith("e") and nid[1:].isdigit():
        return "end"
    if nid.startswith("dec"):
        return "dec"
    if nid.startswith("m") and nid[1:].isdigit():
        return "merge"
    if nid.startswith("fork"):
        return "fork"
    if nid.startswith("join"):
        return "join"
    return "action"


def style_for(kind):
    return {
        "start": "ellipse;whiteSpace=wrap;html=1;fillColor=#d5e8d4;strokeColor=#82b366;fontStyle=1;",
        "end": "ellipse;whiteSpace=wrap;html=1;fillColor=#f8cecc;strokeColor=#b85450;fontStyle=1;",
        "dec": "rhombus;whiteSpace=wrap;html=1;fillColor=#ffe6cc;strokeColor=#d79b00;",
        "merge": "rhombus;whiteSpace=wrap;html=1;fillColor=#ffe6cc;strokeColor=#d79b00;",
        "fork": "line;html=1;strokeWidth=4;strokeColor=#333333;",
        "join": "line;html=1;strokeWidth=4;strokeColor=#333333;",
        "action": "rounded=1;arcSize=12;whiteSpace=wrap;html=1;fillColor=#dae8fc;strokeColor=#6c8ebf;",
    }[kind]


def esc(text):
    return html.escape(str(text), quote=True).replace("\n", "&#xa;")


def vertex(cid, value, style, x, y, w, h):
    return (
        '<mxCell id="%s" value="%s" style="%s" vertex="1" parent="1">'
        '<mxGeometry x="%d" y="%d" width="%d" height="%d" as="geometry"/></mxCell>'
        % (esc(cid), esc(value), style, int(x), int(y), int(w), int(h))
    )


def edge(cid, value, src, tgt, dashed=False):
    style = (
        "edgeStyle=orthogonalEdgeStyle;rounded=0;orthogonalLoop=1;jettySize=auto;"
        "html=1;endArrow=classic;strokeColor=#333333;"
    )
    if dashed:
        style += "dashed=1;"
    return (
        '<mxCell id="%s" value="%s" style="%s" edge="1" parent="1" source="%s" target="%s">'
        '<mxGeometry relative="1" as="geometry"/></mxCell>'
        % (esc(cid), esc(value), style, esc(src), esc(tgt))
    )


def build(diagram):
    lanes = diagram["lanes"]
    lane_idx = {name: i for i, name in enumerate(lanes)}
    width = len(lanes) * LANE_W
    total_h = Y0 + len(diagram["nodes"]) * GAP + 60

    cells = []
    cells.append(
        vertex(
            "title",
            diagram["title"],
            "text;html=1;fontSize=16;fontStyle=1;align=left;verticalAlign=middle;",
            10,
            10,
            max(400, width - 20),
            40,
        )
    )

    for i, lane in enumerate(lanes):
        cells.append(
            vertex(
                "lane%d" % i,
                lane,
                "rounded=0;whiteSpace=wrap;html=1;fillColor=#f7f7f7;strokeColor=#b0b0b0;"
                "verticalAlign=top;fontStyle=1;fontSize=13;spacingTop=8;",
                i * LANE_W,
                60,
                LANE_W,
                total_h - 60,
            )
        )

    for i, (nid, lane, label) in enumerate(diagram["nodes"]):
        kind = kind_of(nid)
        h = DEC_H if kind in ("dec", "merge") else (SE_H if kind in ("start", "end") else ACTION_H)
        if kind in ("fork", "join"):
            h = BAR_H
        x = lane_idx[lane] * LANE_W + (LANE_W - NODE_W) // 2
        y = Y0 + i * GAP
        cells.append(vertex(nid, label, style_for(kind), x, y, NODE_W, h))

    for j, (src, tgt, label) in enumerate(diagram["edges"]):
        dashed = str(label).lower() in ("tidak", "gagal", "ditolak", "salah")
        cells.append(edge("edge%d" % j, label, src, tgt, dashed))

    body = "\n        ".join(cells)
    page_h = total_h + 40
    return (
        '<mxfile host="app.diagrams.net" agent="opencode" version="24.7.17" type="device">\n'
        '  <diagram id="%s" name="%s">\n'
        '    <mxGraphModel dx="1200" dy="900" grid="1" gridSize="10" guides="1" tooltips="1" '
        'connect="1" arrows="1" fold="1" page="1" pageScale="1" pageWidth="%d" pageHeight="%d" '
        'math="0" shadow="0">\n'
        "      <root>\n"
        '        <mxCell id="0"/>\n'
        '        <mxCell id="1" parent="0"/>\n'
        "        %s\n"
        "      </root>\n"
        "    </mxGraphModel>\n"
        "  </diagram>\n"
        "</mxfile>\n"
        % (esc(diagram["name"]), esc(diagram["title"]), width + 40, page_h, body)
    )


def D(name, title, lanes, nodes, edges):
    return {"name": name, "title": title, "lanes": lanes, "nodes": nodes, "edges": edges}


